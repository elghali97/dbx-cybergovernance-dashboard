"""Security Posture publish task (serverless spark_python_task, runs after the refresh task).

Creates or updates the Genie agent and the AI/BI dashboard from the templates generated by tools/build_*.py, then
publishes the dashboard and gives the security group CAN RUN on both. They are not bundle resources because Genie
checks that every table of the agent exists when the space is created, and the tables only exist once the refresh
task has run.

Idempotent: the ids and a hash of what was published are kept in <schema>.published_assets, so an asset is only
updated when its template or settings change (edits made in the UI survive the scheduled runs, not upgrades).
An asset that was deleted is created again.
"""
import argparse
import hashlib
import json
import os

DASHBOARD_NAME = "Databricks Security Posture"
DASHBOARD_TEMPLATE = "dashboards/security_posture.lvdash.json"
GENIE_TEMPLATE = "genie/security_posture.genie.json"


def fill(text, **values):
    for key, value in values.items():
        text = text.replace("${" + key + "}", value)
    return text


def digest(*parts):
    return hashlib.sha256(json.dumps(parts, sort_keys=True).encode()).hexdigest()


class Publisher:
    def __init__(self, spark, w, args):
        self.spark, self.w, self.args = spark, w, args
        self.fq = f"`{args.catalog}`.`{args.schema}`"
        self.state_table = f"{self.fq}.published_assets"

    def api(self, method, path, body=None, query=None):
        return self.w.api_client.do(method, path, query=query, body=body)

    def find(self, path):
        """GET path, or None when the object does not exist (or is in the trash)."""
        from databricks.sdk.errors import NotFound
        try:
            obj = self.api("GET", path)
        except NotFound:
            return None
        return None if obj.get("lifecycle_state") == "TRASHED" else obj

    def load_state(self):
        self.spark.sql(f"CREATE TABLE IF NOT EXISTS {self.state_table} (asset STRING, id STRING, spec_hash STRING, "
                       "updated_at TIMESTAMP) COMMENT 'Dashboard and Genie agent published by the Security Posture job'")
        return {r["asset"]: r for r in self.spark.table(self.state_table).collect()}

    def save_state(self, asset, asset_id, spec_hash):
        self.spark.sql(f"""MERGE INTO {self.state_table} t
                           USING (SELECT :asset AS asset, :id AS id, :hash AS spec_hash) s ON t.asset = s.asset
                           WHEN MATCHED THEN UPDATE SET id = s.id, spec_hash = s.spec_hash, updated_at = current_timestamp()
                           WHEN NOT MATCHED THEN INSERT (asset, id, spec_hash, updated_at)
                                VALUES (s.asset, s.id, s.spec_hash, current_timestamp())""",
                       args={"asset": asset, "id": asset_id, "hash": spec_hash})

    def grant(self, object_type, object_id):
        group = self.args.readers_group
        if not group:
            return
        try:
            self.api("PATCH", f"/api/2.0/permissions/{object_type}/{object_id}",
                     {"access_control_list": [{"group_name": group, "permission_level": "CAN_RUN"}]})
        except Exception as e:
            print(f"WARNING could not give {group} CAN RUN on {object_type}/{object_id}: {str(e).splitlines()[0][:200]}")

    def publish_genie(self, state):
        a = self.args
        template = json.load(open(os.path.join(a.assets_dir, GENIE_TEMPLATE)))
        space = fill(json.dumps(template["serialized_space"]), catalog=a.catalog, schema=a.schema)
        body = {"title": a.name_prefix + template["title"], "description": template["description"],
                "warehouse_id": a.warehouse_id, "serialized_space": space}
        spec_hash = digest(body, a.readers_group)
        previous = state.get("genie")
        space_id = previous["id"] if previous and self.find(f"/api/2.0/genie/spaces/{previous['id']}") else None
        if space_id and previous["spec_hash"] == spec_hash:
            return space_id, "unchanged"
        if space_id:
            self.api("PATCH", f"/api/2.0/genie/spaces/{space_id}", body)
            action = "updated"
        else:
            space_id = self.api("POST", "/api/2.0/genie/spaces", {**body, "parent_path": a.parent_path})["space_id"]
            action = "created"
        self.grant("genie", space_id)
        self.save_state("genie", space_id, spec_hash)
        return space_id, action

    def publish_dashboard(self, state, genie_id):
        from databricks.sdk.errors import AlreadyExists, ResourceAlreadyExists
        a = self.args
        dashboard = json.loads(fill(open(os.path.join(a.assets_dir, DASHBOARD_TEMPLATE)).read(), genie_space_id=genie_id))
        for dataset in dashboard["datasets"]:
            dataset["catalog"], dataset["schema"] = a.catalog, a.schema
        body = {"display_name": a.name_prefix + DASHBOARD_NAME, "warehouse_id": a.warehouse_id,
                "serialized_dashboard": json.dumps(dashboard)}
        spec_hash = digest(body, a.readers_group)
        previous = state.get("dashboard")
        dashboard_id = previous["id"] if previous and self.find(f"/api/2.0/lakeview/dashboards/{previous['id']}") else None
        if dashboard_id and previous["spec_hash"] == spec_hash:
            return dashboard_id, "unchanged"
        action = "updated"
        if not dashboard_id:
            try:
                dashboard_id = self.api("POST", "/api/2.0/lakeview/dashboards", {**body, "parent_path": a.parent_path})["dashboard_id"]
                action = "created"
            except (AlreadyExists, ResourceAlreadyExists):  # no state (new schema): take over the dashboard at the same path
                path = f"{a.parent_path}/{body['display_name']}.lvdash.json"
                dashboard_id = self.api("GET", "/api/2.0/workspace/get-status", query={"path": path})["resource_id"]
        if action == "updated":
            self.api("PATCH", f"/api/2.0/lakeview/dashboards/{dashboard_id}", body)
        self.api("POST", f"/api/2.0/lakeview/dashboards/{dashboard_id}/published",
                 {"warehouse_id": a.warehouse_id, "embed_credentials": False})
        self.grant("dashboards", dashboard_id)
        self.save_state("dashboard", dashboard_id, spec_hash)
        return dashboard_id, action


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", required=True)
    parser.add_argument("--schema", default="security_posture")
    parser.add_argument("--warehouse-id", required=True)
    parser.add_argument("--parent-path", required=True, help="workspace folder of the dashboard and the Genie agent")
    parser.add_argument("--assets-dir", required=True, help="folder with dashboards/ and genie/ templates")
    parser.add_argument("--readers-group", default="", help="group given CAN RUN on the dashboard and the agent")
    parser.add_argument("--name-prefix", default="", help="prefix of the asset names (dev target)")
    args = parser.parse_args()

    from databricks.sdk import WorkspaceClient
    from pyspark.sql import SparkSession
    w = WorkspaceClient()
    p = Publisher(SparkSession.builder.getOrCreate(), w, args)

    w.api_client.do("POST", "/api/2.0/workspace/mkdirs", body={"path": args.parent_path})
    state = p.load_state()
    genie_id, genie_action = p.publish_genie(state)
    dashboard_id, dashboard_action = p.publish_dashboard(state, genie_id)
    host = w.config.host.rstrip("/")
    print(f"Genie agent  {genie_action:<9} {host}/genie/rooms/{genie_id}")
    print(f"Dashboard    {dashboard_action:<9} {host}/dashboardsv3/{dashboard_id}/published")


if __name__ == "__main__":
    main()
